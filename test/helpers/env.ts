export interface SandboxEnvPaths {
  /** Sandbox root (already realpath'd). */
  dir: string;
  home: string;
  tmp: string;
  gitConfigPath: string;
  /** Directory git must not search above. */
  ceiling: string;
}

/**
 * Build the complete child environment. Nothing is inherited except `PATH` (and, on the
 * rare platform that needs them, the dynamic-loader variables).
 *
 * Deliberately absent: `HTTP_PROXY`/`HTTPS_PROXY`/`ALL_PROXY` (a LAN proxy would make
 * `file://` remotes behave strangely), and every ambient `GIT_DIR`/`GIT_WORK_TREE`/
 * `GIT_INDEX_FILE`/`GIT_OBJECT_DIRECTORY` that a wrapping git process might have set.
 */
export function buildSandboxEnv(
  paths: SandboxEnvPaths,
  extra: Record<string, string | undefined> = {},
): Record<string, string> {
  const env: Record<string, string> = {
    PATH: process.env.PATH ?? "/usr/local/bin:/usr/bin:/bin",
    HOME: paths.home,
    TMPDIR: paths.tmp,
    XDG_CONFIG_HOME: `${paths.home}/.config`,
    XDG_CACHE_HOME: `${paths.home}/.cache`,
    XDG_DATA_HOME: `${paths.home}/.local/share`,
    XDG_STATE_HOME: `${paths.home}/.local/state`,

    GIT_CONFIG_GLOBAL: paths.gitConfigPath,
    GIT_CONFIG_SYSTEM: "/dev/null",
    GIT_CEILING_DIRECTORIES: paths.ceiling,
    GIT_TERMINAL_PROMPT: "0",
    GIT_PAGER: "cat",
    PAGER: "cat",
    GIT_AUTHOR_NAME: TEST_USER_NAME,
    GIT_AUTHOR_EMAIL: TEST_USER_EMAIL,
    GIT_COMMITTER_NAME: TEST_USER_NAME,
    GIT_COMMITTER_EMAIL: TEST_USER_EMAIL,

    LC_ALL: "C",
    LANG: "C",
    TZ: "UTC",
    TERM: "dumb",
    COLUMNS: "80",
    NO_COLOR: "1",

    // Mark the process tree as a test run so the CLI can be defensive if it wants.
    OVERGIT_TEST: "1",
  };

  // macOS/Linux loaders occasionally need these; copy only when already present.
  for (const k of ["DYLD_LIBRARY_PATH", "LD_LIBRARY_PATH", "SYSTEMROOT"]) {
    const v = process.env[k];
    if (v) env[k] = v;
  }

  for (const [k, v] of Object.entries(extra)) {
    if (v === undefined) delete env[k];
    else env[k] = v;
  }
  return env;
}
