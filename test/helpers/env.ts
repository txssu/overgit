/**
 * Hermetic environment construction.
 *
 * The developer's real `~/.gitconfig`, their `/etc/gitconfig`, their proxy variables and
 * any ambient `GIT_*` state must not be able to change a test result. Every sandbox gets:
 *
 *   - `GIT_CONFIG_GLOBAL` pointing at a config file the sandbox owns,
 *   - `GIT_CONFIG_SYSTEM=/dev/null`,
 *   - `HOME`/`XDG_*` inside the sandbox,
 *   - `GIT_CEILING_DIRECTORIES` so repo discovery cannot walk out of the sandbox,
 *   - an allowlisted `PATH` and nothing else inherited.
 *
 * Nothing here reaches the network: "remotes" are local bare repos.
 */

import { realpathSync } from "node:fs";
import { tmpdir } from "node:os";

/**
 * The machine's real temp dir, captured at module load and realpath'd.
 *
 * Never call `os.tmpdir()` later: tests legitimately copy a sandbox's env (including
 * `TMPDIR`) into `process.env` so that in-process `src/*` calls are hermetic, and that
 * sandbox is deleted at the end of the test. Anything that read `os.tmpdir()` afterwards
 * would point at a directory that no longer exists.
 */
export const HOST_TMPDIR: string = realpathSync(tmpdir());

